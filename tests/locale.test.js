'use strict';
const assert = require('assert');
const locale = require('../apps/manuk_retro_cluster/locale');
assert.strictEqual(locale.status('speed unavailable; own layers released'), 'Данные скорости недоступны; слои приложения освобождены');
assert.strictEqual(locale.status('gear unavailable or ambiguous; own layers released'), 'Данные передачи недоступны или неоднозначны; слои приложения освобождены');
assert(/Ожидание активного состояния/.test(locale.status('waiting for active vehicle state; own layers released')));
assert(/не установлен или не запущен/.test(locale.status('Retro Cluster off: cluster-render is not installed or not running')));
assert(/подключение/.test(locale.status('Retro Cluster: connecting to cluster-render')));
const active = locale.status('Retro Cluster on: Retro 80s theme, 14 layers on 4 connections, 5.2 MiB of 16 MiB pixels');
assert.strictEqual(active, 'Retro Cluster: включено; Ретро 80-х. Слои: 14; соединения: 4; память изображений: 5,2 из 16 МиБ');
assert.strictEqual(locale.status(active), active);
const waiting = locale.status('Retro Cluster on: Retro 80s theme, 14 layers on 4 connections, 5.2 MiB of 16 MiB pixels, 10 of 14 layers drawn (4 stalled: no frame yet)');
assert(/отображено слоёв: 10 из 14; 4 ожидают содержимого/.test(waiting));
assert(!/stalled|no frame|drawn/.test(waiting));
assert(/экран занят другим приложением/.test(locale.status('Retro Cluster on: Retro 80s theme, 14 layers on 4 connections, 5.2 MiB of 16 MiB pixels, waiting: another app has this display')));
assert(/отклонил слой/.test(locale.status('renderer refused a layer; disable and enable after checking the renderer')));
assert(/Превышен допустимый бюджет/.test(locale.status('layout exceeds conservative renderer budget')));
assert(/ошибка компоновки/.test(locale.status('Retro Cluster: invalid widget data')));
assert.strictEqual(locale.status('Приложение выключено'), 'Приложение выключено');
console.log('PASS Russian RHMI status: unavailable/released/waiting/failure and precise renderer counts');
