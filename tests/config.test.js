'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const os = require('os');
const { ConfigStore, defaults, validate, writeAtomic, toSettings } = require('../apps/manuk_retro_cluster/config');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'retro-config-'));
const log = { error: () => {}, warn: () => {} };
try {
    const c = defaults('car');
    assert.strictEqual(c.enabled, false);
    assert.strictEqual(c.retro.tankLitres, null);
    assert.strictEqual(c.schemaVersion, 7);
    assert.strictEqual(c.widgets, undefined);
    assert.strictEqual(c.startup.onEngineStart, false);
    assert.strictEqual(toSettings(c).demo, 'off');
    assert.strictEqual(toSettings(c).timeZone, 240);
    assert.strictEqual(toSettings(c).clock, '24h');
    assert.throws(() => validate(Object.assign({}, c, { demo: 'auto' })), /unknown key/);
    assert.throws(() => validate(Object.assign({}, c, { layout: 'sport' })), /unsupported/);
    const bad = defaults('car'); bad.timeZone.utcOffsetMinutes = 'Asia/Yerevan';
    assert.throws(() => validate(bad), /unsupported/);
    const badTank = defaults('car'); badTank.retro.tankLitres = 0;
    assert.throws(() => validate(badTank), /invalid value/);
    const unsafe = defaults('car'); unsafe.safety.criticalMaxAgeMs = 2000;
    assert.throws(() => validate(unsafe), /exceed/);
    const store = new ConfigStore(dir, 'car', log);
    let changes = 0;
    const remove = store.onChange(() => changes++);
    c.enabled = true; c.retro.slots['1'] = 'coolant'; store.save(c);
    assert.strictEqual(changes, 1);
    assert.strictEqual(fs.statSync(store.file).mode & 0o777, 0o600);
    assert.strictEqual(new ConfigStore(dir, 'car', log).current.enabled, true);
    assert.strictEqual(new ConfigStore(dir, 'car', log).current.retro.slots['1'], 'coolant');
    const old = fs.readFileSync(store.file, 'utf8');
    assert.throws(() => store.save(badTank));
    assert.strictEqual(fs.readFileSync(store.file, 'utf8'), old);
    fs.writeFileSync(store.file, '{broken'); store.load();
    assert.strictEqual(store.current.enabled, false);
    assert.strictEqual(fs.readFileSync(store.file, 'utf8'), '{broken');
    writeAtomic(store.file, c); store.load();
    assert.strictEqual(store.current.enabled, true);
    assert.strictEqual(store.lastError, null);
    assert(!fs.readdirSync(dir).some((f) => f.indexOf('.tmp-') >= 0));
    store.watch(); const handler = store.watchHandler; store.watch();
    assert.strictEqual(store.watchHandler, handler);
    remove(); store.stop(); store.stop();
    console.log('PASS configuration: strict validation, atomic persistence, restart, fail-closed corrupt file, idempotent watcher');
} finally { fs.readdirSync(dir).forEach((f) => fs.unlinkSync(path.join(dir, f))); fs.rmdirSync(dir); }
