'use strict';
const assert = require('assert');
const motion = require('../apps/manuk_retro_cluster/display_motion');
const m = new motion.DisplayMotion();
assert.strictEqual(m.sample(10, 0, 0, 0), 10, 'first observation is immediate');
assert.strictEqual(m.sample(12, 100, 100, 0), 10);
assert.strictEqual(m.sample(12, 150, 150, 0), 11, 'identical notifications do not restart the transition');
assert.strictEqual(m.sample(12, 200, 200, 0), 12);
assert.strictEqual(m.sample(12, 220, 220, 0), 12, 'no extrapolation beyond the actual received target');
assert.strictEqual(m.sample(15, 250, 250, 0), 12);
assert.strictEqual(m.sample(15, 300, 300, 0), 13.5);
assert.strictEqual(m.sample(14, 300, 300, 0), 13.5, 'retarget from the visible frame without overshoot');
assert.strictEqual(m.sample(14, 400, 400, 0), 14);
assert.strictEqual(m.sample(0, 410, 410, 0), 0, 'zero is never delayed');
assert.strictEqual(m.sample(50, 420, 420, 1), 50, 'new provider epoch snaps even when no missing frame was observed');
assert.strictEqual(m.sample(60, 425, 425, 1), 50);
assert.strictEqual(m.sample(null, 430, null, 1), null, 'invalid/stale data clears the pending transition');
assert.strictEqual(m.sample(30, 450, 450, 1), 30);
assert.strictEqual(m.sample(40, 800, 800, 1), 40, 'a paused render loop cannot replay old animation');
assert.strictEqual(m.sample(60, 0, 0, 1), 60, 'clock rollback resets');
m.clear(); assert.strictEqual(m.value(100), null);
assert.strictEqual(m.sample(10, 100, 100, 0), 10);
assert.strictEqual(m.sample(20, 240, 120, 0), 20, 'already delayed samples are not given a new animation delay');
assert.strictEqual(motion.TRANSITION_MS, 100);
assert.strictEqual(motion.FRAME_MS, 34);
console.log('display motion: bounded interpolation, invalidation, epoch/clock reset, zero and no extrapolation OK');
