'use strict';
const assert = require('assert');
const { adapter, IF } = require('../bench/profile-signals');
const fixture = require('../bench/profiles-fixture.json').signals;
const received = [], changes = [], notifications = {}, subs = {};
Object.keys(IF).forEach(k => { subs[IF[k]] = [{ res: { available: false } }]; notifications[IF[k]] = [on => changes.push([k, on])]; });
const transport = adapter({ subs, feed: (iface, field, value) => received.push({ iface, field, value }) }, notifications);
const field = name => received.filter(r => r.field === name).slice(-1)[0].value;
transport.tick(fixture, 1);
assert.equal(field('statusFESVehicleDynamicSwitchHMI').actualValueModeDrivingExperience, 1);
assert.deepStrictEqual(field('statusGearboxDrive'), { statusActualGearDrive: 'G4', statusActualStageDrive: 'D' });
assert.equal(transport.values(fixture, 'manual').dsc, 'ON');
assert.equal(transport.values(fixture, 'manual').gearboxProgram, 'D');
transport.tick(Object.assign({}, fixture, { selector: 'P', gear: null, gearboxProgram: 'S' }), 4);
assert.deepStrictEqual(field('statusGearboxDrive'), { statusActualGearDrive: 'N_OR_P', statusActualStageDrive: 'P' });
assert.equal(field('dataDisplayGearbox').displayProgramGearbox, 'S_MINUS_PROGRAMM');
transport.tick(Object.assign({}, fixture, { pFL: null, tFL: null }), 7);
assert.equal(field('statusTyrePressure').actualValuePressureTyreFLH, 65535);
assert.equal(field('statusTyrePressure').actualValuePressureTyreFRH, 23);
assert.equal(field('statusTyreTemperature').actualValueTemperatureTyreFLH, 65535);
const before = received.length;
transport.source('speed', false);
transport.tick(fixture, 1);
assert.equal(received.slice(before).some(r => r.iface === IF.speed), false);
assert.equal(subs[IF.speed][0].res.available, false);
assert.equal(transport.values(fixture, 'manual').speed, null);
assert.equal(transport.values(fixture, 'manual').dsc, 'ON');
transport.source('speed', true);
transport.tick(fixture, 1);
assert.equal(field('statusCarSpeed2').speedVehicleCentreOfGravity, 88 / 0.015625);
transport.missing();
assert(Object.keys(subs).every(iface => subs[iface][0].res.available === false));
assert.equal(transport.values(fixture, 'missing').dsc, null);
assert.equal(transport.values(fixture, 'missing').simulateCarSafety, true);
assert.equal(transport.values(Object.assign({}, fixture, { condition: 5 }), 'manual').engineProfile, null);
transport.tick({}, null);
assert.equal(field('statusCarSpeed2').speedVehicleCentreOfGravity, 65535);
assert.equal(field('statusEngineTemperature').temperatureEngineOilDrive, 255);
assert.equal(field('statusFESVehicleDynamicSwitchHMI').actualValueModeDrivingExperience, 255);
assert(changes.some(c => c[0] === 'speed' && c[1] === false));
console.log('PASS bench transport: independent mode/selector/program/DSC, one missing wheel/source, lifecycle and no invented numeric defaults');
