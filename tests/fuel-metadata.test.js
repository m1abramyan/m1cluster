'use strict';
const assert = require('assert');
const Source = require('../apps/manuk_retro_cluster/retro_source');
const config = require('../apps/manuk_retro_cluster/config');
const probe = require('../tools/inspect-signals');
let now = 1000, cfg = config.defaults('car');
const s = new Source({}, () => cfg, { now: () => now });
const tank = (value) => { const next = JSON.parse(JSON.stringify(cfg)); next.retro.tankLitres = value; cfg = config.validate(next); };
const feed = (value) => s.receive('fuel', 'statusRangeTankStatus', { fluidLevelFuelTank: value });
s.receive('condition', 'VehicleCondition', { statusConditionVehicle: 10 });
assert.strictEqual(cfg.retro.tankLitres, null);
assert.strictEqual(s.reading('fuelPct').value, null);
assert(/fuelL is not a current valid/.test(s.reading('fuelPct').reason), 'missing litres are not reported as a capacity-only problem');
const before = probe.snapshot(s);
assert.strictEqual(before.providers.fuel.available, false);
feed(30);
let r = s.reading('fuelPct');
assert.strictEqual(r.value, null); assert.strictEqual(r.unit, '%'); assert.strictEqual(r.quality, 'unavailable');
assert(/tankLitres is not confirmed/.test(r.reason));
assert.strictEqual(s.read('fuelL'), 30, 'unknown capacity does not hide the valid litre source');
const after = probe.snapshot(s);
assert.strictEqual(after.providers.fuel.available, true);
assert.strictEqual(after.readings.fuelL.raw, 30);
assert.strictEqual(after.readings.fuelPct.reason, r.reason, 'semicolon in a useful diagnostic reason remains visible');
tank(60); r = s.reading('fuelPct');
assert.strictEqual(r.value, 50); assert.strictEqual(r.quality, 'derived');
assert.strictEqual(r.receivedAt, now); assert.strictEqual(r.raw, 30);
assert(/KombiIF.statusRangeTankStatus.fluidLevelFuelTank/.test(r.source));
assert(/config.retro.tankLitres/.test(r.source)); assert.strictEqual(r.formula, '100 * fuelL / configured tankLitres');
assert.strictEqual(s.data().fuelPct, 50); assert.strictEqual(s.diagnostics().readings.fuelPct.value, 50);
assert(!Object.prototype.hasOwnProperty.call(s.values, 'fuelPct'), 'percentage is computed from the current observation, never stored separately');
feed(0); assert.strictEqual(s.read('fuelPct'), 0); assert.strictEqual(s.reading('fuelPct').quality, 'derived');
feed(60); assert.strictEqual(s.read('fuelPct'), 100);
feed(61); assert.strictEqual(s.read('fuelPct'), null); assert.strictEqual(s.reading('fuelPct').quality, 'invalid');
assert(/exceeds configured/.test(s.reading('fuelPct').reason), 'bad capacity/source agreement is not silently clamped in the report');
[undefined, null, '30', 255, -1, NaN].forEach(raw => { feed(raw); assert.strictEqual(s.read('fuelPct'), null); assert(/fuelL is not/.test(s.reading('fuelPct').reason)); });
feed(30); now += 35001;
assert.strictEqual(s.read('fuelPct'), null); assert.strictEqual(s.reading('fuelPct').quality, 'stale');
feed(30); s.availability('fuel', false);
assert.strictEqual(s.read('fuelPct'), null); assert.strictEqual(s.reading('fuelPct').quality, 'unavailable');
s.availability('fuel', true); assert.strictEqual(s.read('fuelPct'), null, 'availability alone cannot restore an old observation');
feed(30); assert.strictEqual(s.read('fuelPct'), 50);
s.receive('condition', 'VehicleCondition', { statusConditionVehicle: 12 });
assert.strictEqual(s.read('fuelPct'), null);
s.receive('condition', 'VehicleCondition', { statusConditionVehicle: 10 });
assert.strictEqual(s.read('fuelPct'), null);
feed(30); tank(null); assert.strictEqual(s.read('fuelPct'), null);
[-1, 0, 201, '60'].forEach(value => assert.throws(() => tank(value), /invalid value/));
assert.strictEqual(cfg.retro.tankLitres, null);
// Existing temperature payloads are recorded per member. A missing/invalid oil
// member must be visible as such, not replaced by the previous valid number.
s.receive('cds', 'statusEngineTemperature', { temperatureEngineOilDrive: 148, temperatureEngineDrive: 138 });
let temperatures = probe.snapshot(s).readings;
assert.strictEqual(temperatures.oil.raw, 148); assert.strictEqual(temperatures.oil.value, 100);
assert.strictEqual(temperatures.coolant.raw, 138); assert.strictEqual(temperatures.coolant.value, 90);
s.receive('cds', 'statusEngineTemperature', { temperatureEngineOilDrive: 255, temperatureEngineDrive: 139 });
temperatures = probe.snapshot(s).readings;
assert.strictEqual(temperatures.oil.raw, 255); assert.strictEqual(temperatures.oil.quality, 'invalid');
assert.strictEqual(temperatures.oil.value, null); assert.strictEqual(temperatures.coolant.value, 91);
s.receive('cds', 'statusEngineTemperature', { temperatureEngineDrive: 140 });
assert.strictEqual(s.read('oil'), null); assert.strictEqual(s.read('coolant'), 92);
s.stop(); assert.strictEqual(s.read('fuelPct'), null);
const restarted = new Source({}, () => cfg);
assert.strictEqual(restarted.read('fuelPct'), null);
assert.strictEqual(Object.keys(Source.IF).length, 12, 'no provider or vehicle operation added');
console.log('PASS fuel metadata: litres vs unknown capacity, explicit-capacity derived percent, zero/sentinel/stale/epoch/sleep, late availability and separate raw oil/coolant report');
